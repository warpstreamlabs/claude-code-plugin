"""Checks scripts/estimate.py against figures produced by the website calculator.

tests/fixtures/website_reference.json is generated by running the calculator
JavaScript from warpstream.com/pricing (see website_harness.mjs). Run with:

  python3 -m unittest discover -s tests
"""

import json
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import estimate  # noqa: E402

FIXTURES = os.path.join(ROOT, "tests", "fixtures", "website_reference.json")
PRICING = estimate.load_pricing()
SERVERLESS = {"kafka-msk-serverless", "kafka-kinesis"}


def plugin_figures(inputs):
    """The plugin's result for one reference case, keyed by the website's element ids."""
    r = estimate.estimate(
        write_mibs=inputs["write_mibs"],
        retention_days=inputs["retention_days"],
        partitions=inputs["partitions"],
        tier=inputs["tier"],
        low_latency=inputs["low_latency"],
        fetch_from_follower=inputs["fetch_from_follower"],
        tiered_storage=inputs["tiered_storage"],
        compare=[inputs["comparison"]],
        pricing=PRICING,
    )
    d = estimate.dollars
    w = r["warpstream"]
    dp, cp = w["data_plane"], w["control_plane"]
    c = r["comparisons"][0]
    out = {
        "warpstream-cumulative-cost": d(w["total"]),
        "data-plane-cost": d(dp["total"]),
        "control-plane-cost": d(cp["total"]),
        "num-agents": str(dp["agents"]["count"]),
        "agent-instance-type": dp["agents"]["instance_type"],
        "agents-cost": d(dp["agents"]["cost"]),
        "object-storage-api-cost": d(dp["object_storage_api"]),
        "storage-cost": d(dp["object_storage"]["cost"]),
        "s3-express-bandwidth-cost-cost": d(dp["s3_express_bandwidth"]),
        "warpstream-cluster-minutes-cost": d(cp["cluster_minutes"]),
        "uncompressed-writes-cost": d(cp["writes"]["cost"]),
        "uncompressed-warpstream-storage-cost": d(cp["storage"]["cost"]),
        "warpstream-savings-percent": str(c["savings_percent"]),
        "kafka-total-cost": d(c["total"]),
        "serverless-total-cost": d(c["total"]),
    }
    k = c["costs"]
    if inputs["comparison"] in SERVERLESS:
        out.update({
            "serverless-cluster-hours-cost": d(k["cluster_hours"]),
            "serverless-partition-hours-cost": d(k["partition_hours"]),
            "serverless-write-throughput-cost": d(k["write_throughput"]),
            "serverless-read-throughput-cost": d(k["read_throughput"]),
            "serverless-storage-cost": d(k["storage"]),
        })
    else:
        out.update({
            "num-kafka-brokers": str(c["brokers"]["count"]),
            "kafka-broker-instance-type": c["brokers"]["instance_type"],
            "kafka-brokers-cost": d(k["brokers"]),
            "kafka-interzone-networking": d(k["inter_zone"]),
            "kafka-ebs-storage-cost": d(k["local_storage"]),
            "kafka-tiered-storage-cost": d(k["tiered_storage"]),
            "node-count-limiting-factor": c["brokers"]["limited_by"],
        })
        if inputs["comparison"] == "kafka-msk-express":
            out["kafka-write-throughput-cost"] = d(k["data_in"])
    return out


# The website shows GCP's per-vCPU unit as "DCU"; the plugin spells it out.
INSTANCE_LABELS = {"vCPU (DCU)": "DCU"}


class MatchesWebsite(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with open(FIXTURES, encoding="utf-8") as f:
            cls.cases = json.load(f)["cases"]

    def test_every_comparison_is_covered(self):
        seen = {c["inputs"]["comparison"] for c in self.cases}
        self.assertEqual(seen, set(PRICING["comparison_order"]))

    def test_reference_cases(self):
        for case in self.cases:
            inputs = case["inputs"]
            with self.subTest(**inputs):
                ours = plugin_figures(inputs)
                k = ours.get("kafka-broker-instance-type")
                if k in INSTANCE_LABELS:
                    ours["kafka-broker-instance-type"] = INSTANCE_LABELS[k]
                expected = {key: case["website"][key] for key in ours}
                self.assertEqual(ours, expected)


class PlanSanityCheck(unittest.TestCase):
    def test_ten_mibs_fundamentals(self):
        # PLAN.md §6.1: 10 MiB/s, 7 days, Fundamentals -> $253 writes + $59 storage
        # + cluster minutes. The calculator charges the $500 tier price for a full month.
        r = estimate.estimate(write_mibs=10, retention_days=7, tier="fundamentals", compare=[], pricing=PRICING)
        cp = r["warpstream"]["control_plane"]
        self.assertEqual((cp["writes"]["cost"], cp["storage"]["cost"], cp["cluster_minutes"]), (253, 59, 500))
        self.assertEqual(cp["total"], 812)


class Behaviour(unittest.TestCase):
    def test_enterprise_needs_sales(self):
        with self.assertRaises(ValueError):
            estimate.estimate(tier="enterprise", pricing=PRICING)

    def test_partitions_above_tier_limit_warn_but_are_kept(self):
        r = estimate.estimate(partitions=20000, tier="fundamentals", compare=[], pricing=PRICING)
        self.assertEqual(r["inputs"]["partitions_used"], 20000)
        self.assertTrue(any("default limit" in n for n in r["notes"]))

    def test_high_throughput_raises_partitions(self):
        r = estimate.estimate(write_mibs=1000000, partitions=256, compare=[], pricing=PRICING)
        self.assertEqual(r["inputs"]["partitions_used"], 28672)

    def test_redpanda_has_no_price(self):
        r = estimate.estimate(compare=["redpanda"], pricing=PRICING)
        self.assertIsNone(r["comparisons"][0]["total"])
        self.assertIn("utm_source=claude", r["comparisons"][0]["compare_url"])

    def test_write_tier_boundaries(self):
        tiers = PRICING["warpstream"]["kafka"]["write_tiers"]
        self.assertAlmostEqual(estimate.tiered_cost(51200, tiers, "price_per_gib"), 512)
        self.assertAlmostEqual(estimate.tiered_cost(51201, tiers, "price_per_gib"), 512.0075)

    def test_renderers(self):
        r = estimate.estimate(write_mibs=10, compare=None, schema_registry=True, tableflow_mibs=5, pricing=PRICING)
        for render in (estimate.render_text, estimate.render_markdown, estimate.render_html):
            out = render(r)
            self.assertIn("estimate, not a quote", out)
            self.assertIn(r["last_verified"], out)


if __name__ == "__main__":
    unittest.main()
